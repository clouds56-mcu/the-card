def physical_ref(semantic_ref):
    """Translate a semantic passive name to its conventional designator."""
    if semantic_ref.startswith(("R_", "C_")):
        return SEMANTIC_REFS[semantic_ref]
    return SEMANTIC_REFS.get(semantic_ref, semantic_ref)


# ─────────────────────────────────────────────────────────────────────────────
# Helpers (always connect via NET += pin, which handles multi-pin pinlists)
# ─────────────────────────────────────────────────────────────────────────────
def part(key, value=None, footprint=None):
    lib, name = SYM[key]
    p = Part(lib, name, footprint=footprint)
    p.ref = REF[key]
    if value is not None:
        p.value = value
    return p


def R(value, ref):
    r = Part(GEN, "0402WGF1002TCE", footprint=R_FP)
    r.ref, r.value = physical_ref(ref), value
    return r


def C(value, ref, size="0402"):
    lib, name, _ = C0402 if size == "0402" else C0603
    c = Part(lib, name, footprint=C_FP[size])
    c.ref, c.value = physical_ref(ref), value
    return c


def std_part(library, name, value, ref, footprint):
    """Create a part from KiCad's standard symbol libraries."""
    component = Part(library, name, footprint=footprint)
    component.ref, component.value = ref, value
    return component


def decouple(net, ref, size="0402"):
    """100nF (or 10µF for 0603) from `net` to gnd."""
    c = C("100nF" if size == "0402" else "10uF", ref, size)
    net += c[1]
    c[2] += gnd
    return c


