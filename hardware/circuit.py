decouple(p3v3, "C_imu1"); decouple(p3v3, "C_imu2", "0603")


# ─────────────────────────────────────────────────────────────────────────────
# Temp/Humidity SHT40 (U4) — always-on rail
# ─────────────────────────────────────────────────────────────────────────────
