# ─────────────────────────────────────────────────────────────────────────────
imu = part("U3_IMU")
p3v3 += imu["VDD"]; p3v3 += imu["VDDIO"]; gnd += imu["GND"]
i2c_scl += imu["SCL"]; i2c_sda += imu["SDA"]
imu_int += imu["INT1"]
p3v3 += imu["CS"]              # CS high -> I2C mode
